#!/usr/bin/env bash
# Generates the header that ENRMLibraryTests.mm pulls in, so an example app's
# test target picks up every XCTest source under
# packages/react-native-enriched-markdown/__tests__/ios without a project.pbxproj
# edit per file. Used by EnrichedMarkdownExampleTests (CocoaPods) and
# EnrichedMarkdownSpmExampleTests (Swift Package Manager).
#
# Why this exists: both example projects are objectVersion 54 and list sources
# explicitly, so a new test file would otherwise need a PBXFileReference, a
# PBXBuildFile, a group entry and a Sources-phase entry before it ever compiled -
# and a file nobody wired stayed silently unrun, which is exactly how the lane
# passed while covering nothing. Gradle auto-discovers src/test/java on Android;
# this gives the iOS lanes the same property.
#
# The discovered sources are #included into one umbrella translation unit rather
# than compiled separately, because the Sources phase is what we are avoiding
# touching. Consequence: file-scope helpers in these sources share one
# namespace, so name them distinctly (the ENRM prefix already does this for
# classes).
#
# --spm-package <dir>: also #define, above the includes, the flags that the
# library's Package.swift sets for its ReactNativeEnrichedMarkdown target
# (ENRICHED_MARKDOWN_MATH/VIDEO/CODE_HIGHLIGHT, ENRM_GRAMMAR_*). They follow the
# app's "enriched-markdown" config, so a header that branches on them, such as
# ENRMFeatureFlags.h, must see the same values in the tests as in the library.
# No header the tests include does so yet; this keeps them in step once one does.
#
# Run as a build phase on the test target (before Sources); DERIVED_FILE_DIR is
# supplied by Xcode. It can also be run by hand with DERIVED_FILE_DIR set.
set -euo pipefail

spm_package=""
while [ $# -gt 0 ]; do
  case "$1" in
    --spm-package)
      spm_package="$2"
      shift 2
      ;;
    *)
      echo "Unknown argument: $1" >&2
      exit 1
      ;;
  esac
done

script_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
repo_root="$(cd "$script_dir/../.." && pwd)"
tests_dir="$repo_root/packages/react-native-enriched-markdown/__tests__/ios"

if [ -z "${DERIVED_FILE_DIR:-}" ]; then
  echo "DERIVED_FILE_DIR is not set; run this from an Xcode build phase." >&2
  exit 1
fi

out="$DERIVED_FILE_DIR/ENRMGeneratedTestSources.h"
mkdir -p "$DERIVED_FILE_DIR"

echo "// Generated by scripts/ios/generate-rn-test-sources.sh. Do not edit." >"$out.new"

if [ -n "$spm_package" ]; then
  manifest=$(env -i HOME="$HOME" PATH="/usr/bin:/bin:/usr/sbin:/sbin" \
    ${DEVELOPER_DIR:+DEVELOPER_DIR="$DEVELOPER_DIR"} \
    xcrun swift package dump-package \
    --package-path "$spm_package" \
    --scratch-path "$DERIVED_FILE_DIR/spm-manifest")
  defines=$(printf '%s' "$manifest" | jq -r '
    .targets[] | select(.name == "ReactNativeEnrichedMarkdown")
    | .settings[] | select(.tool == "cxx" and .condition == null and .kind.define != null)
    | .kind.define._0')
  if [ -z "$defines" ]; then
    echo "No defines found for ReactNativeEnrichedMarkdown in $spm_package/Package.swift." >&2
    exit 1
  fi
  while IFS= read -r define; do
    name="${define%%=*}"
    value=1
    if [ "$name" != "$define" ]; then
      value="${define#*=}"
    fi
    echo "#define $name $value" >>"$out.new"
  done <<<"$defines"
  echo "Defined $(printf '%s\n' "$defines" | wc -l | tr -d ' ') flag(s) from $spm_package/Package.swift"
fi

count=0
if [ -d "$tests_dir" ]; then
  while IFS= read -r file; do
    echo "#include \"$file\"" >>"$out.new"
    count=$((count + 1))
  done < <(find "$tests_dir" -maxdepth 1 -type f \( -name '*.m' -o -name '*.mm' \) | sort)
fi

if [ "$count" -eq 0 ]; then
  echo "// No XCTest sources found in $tests_dir." >>"$out.new"
fi

if [ -f "$out" ] && cmp -s "$out" "$out.new"; then
  rm -f "$out.new"
else
  mv "$out.new" "$out"
fi

echo "Wired $count iOS test source(s) from $tests_dir"
